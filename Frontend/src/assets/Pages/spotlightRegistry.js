/**
 * Intelligent Spotlight Query Matcher
 * Supports exact prefix, tokenized fuzzy matching, synonym search, and category filtering.
 */
export function searchSpotlightRegistry(query = "", category = "all") {
    const cleanQ = query.toLowerCase().trim();
    const tokens = cleanQ.split(/\s+/).filter(Boolean);

    return SPOTLIGHT_REGISTRY.filter(item => {
        // Category filtering
        if (category !== "all" && item.categoryType !== category) {
            return false;
        }

        if (!cleanQ) return true;

        // Check if every token matches at least one property
        return tokens.every(token => {
            const inTitle = item.title.toLowerCase().includes(token);
            const inModule = item.module.toLowerCase().includes(token);
            const inParent = item.parentMenu.toLowerCase().includes(token);
            const inCategory = item.categoryLabel.toLowerCase().includes(token);
            const inDesc = item.description.toLowerCase().includes(token);
            const inTags = item.tags.some(tag => tag.toLowerCase().includes(token));
            const inActions = item.keyActions ? item.keyActions.some(act => act.toLowerCase().includes(token)) : false;

            return inTitle || inModule || inParent || inCategory || inDesc || inTags || inActions;
        });
    });
}
